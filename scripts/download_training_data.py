"""Download the regenerated OpenPerfectBlend training set from Hugging Face.

The released sets are the exact training data used in the paper: every assistant
turn of OpenPerfectBlend regenerated by the target model (thinking disabled).

  qwen3-8b -> wingchiuloong/OpenPerfectBlend-Qwen3-8B-Regen
  qwen3-4b -> wingchiuloong/OpenPerfectBlend-Qwen3-4B-Regen

The parquet shards are converted to the same JSONL layout that
``scripts/prepare_training_data.sh`` produces, at the path the launch scripts
under ``examples/colocated/`` read by default:

  cache/dataset/perfectblend/perfectblend_train_regen_<qwen3_8b|qwen3_4b>.jsonl

``train.sh`` calls this automatically when that file is missing.

Usage::

    python scripts/download_training_data.py qwen3-8b
    python scripts/download_training_data.py qwen3-4b --output /path/to/train.jsonl
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import pyarrow.parquet as pq
from huggingface_hub import snapshot_download

ROOT = Path(__file__).resolve().parents[1]
HF_REPOS = {
    "qwen3-8b": "wingchiuloong/OpenPerfectBlend-Qwen3-8B-Regen",
    "qwen3-4b": "wingchiuloong/OpenPerfectBlend-Qwen3-4B-Regen",
}


def default_output(model: str) -> Path:
    label = model.replace("-", "_")
    return ROOT / "cache" / "dataset" / "perfectblend" / f"perfectblend_train_regen_{label}.jsonl"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("model", choices=sorted(HF_REPOS))
    parser.add_argument("--output", type=Path, help="output JSONL (default: the path train.sh expects)")
    parser.add_argument("--force", action="store_true", help="re-download even if the output exists")
    parser.add_argument("--keep-parquet", action="store_true", help="keep the downloaded parquet shards")
    args = parser.parse_args()

    out = (args.output or default_output(args.model)).resolve()
    if out.exists() and not args.force:
        print(f"{out} already exists; skipping (use --force to re-download)")
        return

    repo = HF_REPOS[args.model]
    # Shards go next to the output so an interrupted download resumes on rerun.
    shard_dir = out.parent / f".{out.stem}.parquet"
    out.parent.mkdir(parents=True, exist_ok=True)
    print(f"Downloading {repo} -> {shard_dir}")
    snapshot_download(
        repo_id=repo,
        repo_type="dataset",
        allow_patterns=["*.parquet"],
        local_dir=str(shard_dir),
    )
    shards = sorted(shard_dir.rglob("*.parquet"))
    if not shards:
        raise SystemExit(f"no parquet shards found in {repo}")

    # Write to a temp file first so a partial conversion never passes for real data.
    tmp = out.with_name(out.name + ".tmp")
    rows = 0
    with tmp.open("w", encoding="utf-8") as f:
        for shard in shards:
            for batch in pq.ParquetFile(shard).iter_batches(batch_size=10_000):
                for row in batch.to_pylist():
                    f.write(json.dumps(row, ensure_ascii=False) + "\n")
                    rows += 1
            print(f"  converted {shard.name} ({rows} rows so far)")
    tmp.replace(out)

    if not args.keep_parquet:
        shutil.rmtree(shard_dir)
    print(f"Wrote {rows} rows to {out}")


if __name__ == "__main__":
    main()
